HDR = "-- GATE PACK %s (%s). Read-only catalog SELECT, no writes, no table data. Generated by gate-packs/mkpacks.py; do not edit by hand.\n"


def q(s):
    return "'%s'" % s


def arr(items):
    return "array[" + ", ".join(q(i) for i in items) + "]"


def tbl_priv_sql(tables):
    cols = ", ".join("case when has_table_privilege(r.role, c.oid, '%s') then '%s' end" % (p.upper(), p) for p in
                     ("select", "insert", "update", "delete", "truncate", "references", "trigger"))
    return ("select c.relname as obj, r.role, coalesce(concat_ws(',', %s), '') as privs, c.relrowsecurity as rls\n"
            "from pg_catalog.pg_class c\n"
            "cross join (values ('anon'), ('authenticated'), ('service_role')) as r(role)\n"
            "where c.oid in (%s)\n"
            "order by 1, 2;\n" % (cols, ", ".join("pg_catalog.to_regclass('%s')" % t for t in tables)))


def seq_priv_sql(seqs):
    cols = ", ".join("case when has_sequence_privilege(r.role, c.oid, '%s') then '%s' end" % (p.upper(), p.lower()) for p in ("usage", "select", "update"))
    return ("select c.relname as obj, r.role, coalesce(concat_ws(',', %s), '') as privs\n"
            "from pg_catalog.pg_class c\n"
            "cross join (values ('anon'), ('authenticated'), ('service_role')) as r(role)\n"
            "where c.oid in (%s)\n"
            "order by 1, 2;\n" % (cols, ", ".join("pg_catalog.to_regclass('%s')" % t for t in seqs)))


def fn_sql(sigs):
    return ("select p.proname as obj, pg_catalog.oidvectortypes(p.proargtypes) as args, p.prosecdef as definer,\n"
            "  coalesce((select substr(c, 13) from unnest(coalesce(p.proconfig, '{}')) c where c like 'search_path=%%'), '') as search_path,\n"
            "  coalesce((select string_agg(r, ',' order by r) from (values ('anon'), ('authenticated'), ('service_role')) as x(r)\n"
            "            where has_function_privilege(x.r, p.oid, 'EXECUTE')), '') as exec_roles,\n"
            "  exists (select 1 from aclexplode(coalesce(p.proacl, acldefault('f', p.proowner))) a where a.grantee = 0 and a.privilege_type = 'EXECUTE') as exec_public\n"
            "from pg_catalog.pg_proc p\n"
            "where p.oid in (%s)\n"
            "order by 1, 2;\n" % ", ".join("pg_catalog.to_regprocedure('%s')" % s for s in sigs))


def pol_sql(schema, tables):
    return ("select tablename as obj, policyname, cmd, permissive, array_to_string(roles, ',') as roles\n"
            "from pg_catalog.pg_policies\n"
            "where schemaname = '%s' and tablename in (%s)\n"
            "order by 1, 2;\n" % (schema, ", ".join(q(t) for t in tables)))


def trg_sql(names):
    return ("select c.relname as obj, t.tgname, t.tgenabled::text as enabled, (t.tgtype & 1) = 1 as row_level, (t.tgtype & 2) = 2 as before_trg\n"
            "from pg_catalog.pg_trigger t join pg_catalog.pg_class c on c.oid = t.tgrelid\n"
            "where not t.tgisinternal and t.tgname in (%s)\n"
            "order by 1, 2;\n" % ", ".join(q(n) for n in names))


def pre_sql(label, exprs):
    body = ",\n".join("  coalesce((%s), false) as %s" % (e, k) for k, e in exprs)
    return (HDR % (label, "PRE-APPLY preflight")
            + "-- EXPECTED PASS: at_hosted___BEFORE_MAX__ = 1 and every other column true. STOP CONDITION: any column differs.\n"
            "with chain_guard as (\n"
            "  select 1 / (case when (select max(version) from supabase_migrations.schema_migrations) = '__BEFORE_MAX__' then 1 else 0 end) as at_hosted___BEFORE_MAX__\n"
            ")\nselect g.at_hosted___BEFORE_MAX__,\n" + body + "\nfrom chain_guard g;\n")


JS_HELP = r'''
const cmp = (got, want, what) => { if (JSON.stringify([...got].sort()) !== JSON.stringify([...want].sort())) fail(`${what}: got ${JSON.stringify(got)}, expected ${JSON.stringify(want)}`); };
const tb = (name) => rows(name).map((x) => `${x.obj}|${x.role}|${x.privs}|${isTrue(x.rls)}`);
const fnr = (name) => rows(name).map((x) => `${x.obj}(${x.args})|definer=${isTrue(x.definer)}|sp=${x.search_path}|exec=${x.exec_roles}|public=${isTrue(x.exec_public)}`);
const fnx = (name) => rows(name).map((x) => `${x.obj}(${x.args})|exec=${x.exec_roles}|public=${isTrue(x.exec_public)}`);
const plx = (name) => rows(name).map((x) => `${x.obj}|${x.policyname}|${x.cmd}|${x.permissive}`);
const pl = (name) => rows(name).map((x) => `${x.obj}|${x.policyname}|${x.cmd}|${x.permissive}|${x.roles}`);
const sq = (name) => rows(name).map((x) => `${x.obj}|${x.role}|${x.privs}`);
const tg = (name) => rows(name).map((x) => `${x.obj}|${x.tgname}|${x.enabled}|row=${isTrue(x.row_level)}|before=${isTrue(x.before_trg)}`);
'''


def tbl_expect(table, **by_role):
    return ["%s|%s|%s|true" % (table, r, by_role.get(r, "")) for r in ROLES]


def write_pack(ver, pre_label, pre_exprs, sql_files, checks, tables, verify_label, requires=None, notes=""):
    d = os.path.join(OUT, ver)
    os.makedirs(d, exist_ok=True)
    for f in os.listdir(d):
        if f.endswith(".sql") or f.endswith(".part") or f == "pack.json":
            os.remove(os.path.join(d, f))
    open(os.path.join(d, "g12-preflight.sql"), "w").write(pre_sql(pre_label, pre_exprs))
    names = []
    for i, (nm, sql) in enumerate(sql_files, 1):
        fn = "c%02d_%s.sql" % (i, nm)
        names.append(fn)
        open(os.path.join(d, fn), "w").write(HDR % (ver + " " + nm, "POST-APPLY read-back") + sql)
    js = JS_HELP + "\n".join(checks) + "\n"
    open(os.path.join(d, "verify-pre.js.part"), "w").write("")
    open(os.path.join(d, "verify-body.js.part"), "w").write(js)
    pj = {"migration": ver, "tables": tables, "preflight": {"sql": "g12-preflight.sql", "fields": [k for k, _ in pre_exprs]},
          "verify_sql": names, "verify_label": verify_label, "notes": notes}
    if requires:
        pj["requires_before_max"] = requires
    json.dump(pj, open(os.path.join(d, "pack.json"), "w"), indent=2)
    open(os.path.join(d, "pack.json"), "a").write("\n")
    if tables:
        for ref in ("open.sql.ref", "w03.sql.ref"):
            src = os.path.join(HERE, "0254", ref)
            open(os.path.join(d, ref), "w").write(open(src).read())


def check(label, name, fn, want):
    return ('cmp(%s("%s"), %s, "%s");\nconsole.log("PASS %s");' % (fn, name, json.dumps(list(want)), label, label))


def exists_fn(sig):
    return "pg_catalog.to_regprocedure('%s') is not null" % sig


def absent_fn(sig):
    return "pg_catalog.to_regprocedure('%s') is null" % sig


