"""Writes the gate packs for 0253, 0258, 0266 and 0271 (deterministic; the output is committed and reviewed).

A pack is: pack.json, one PRE-apply preflight SELECT (booleans, every one must be true; the chain guard names the hosted max
it is run at), a few POST-apply read-only SELECTs (privilege matrices, policy lists, function and trigger facts) and the node
check that compares those results with the EXPECTED values written below. Everything is read-only catalog SQL.
The expected values come from the reviewers' stated checks (Insurance PEER-0271-FINAL C3 and PEER-0253-SQL, Privacy
PEER-0258-0266-SQL C4) and are checked against the sealed bodies by builder-check.sh and against a real stack in CI.
"""
