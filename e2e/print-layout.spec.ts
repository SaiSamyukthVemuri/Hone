import { test, expect, type Page } from "@playwright/test";
import { PDFDocument } from "pdf-lib";
import { loginAsOwner } from "./helpers/flows";
import { seedE2eStudio, seedE2eClient, getE2eServiceId, getOwnerPractitionerId, seedE2eProbeInventoryItem, seedE2eOverdueDisinfectant, sql, type E2eSeed } from "./helpers/seed";

// What a person gets when they print or "Save as PDF" the app's printable documents: the client statement, the record-keeping sections and the
// clinical-notes export. Synthetic data only. Each document is rendered in PRINT media at the printable width of a Letter and of an A4 sheet (the sheet less 0.5 in margins), in the light theme
// and with the (future) dark theme class on <html>, and must be:
//   - not clipped: nothing sticks out past the sheet's width;
//   - only the document: no app navigation, footer, button or link prints (a document's OWN header inside <main> is allowed);
//   - readable: every piece of text is dark enough against white paper (print has background graphics off by default), whatever the screen theme;
//   - a real PDF at the sheet's size, with more than one page for the long documents, and the statement's totals present in its text.
// The PDF is made with a 0.5 in margin, as a browser print dialog does by default. The receipt PDF is generated by pdf-lib at a fixed Letter size (lib/billing/receipt-pdf.ts) and is not an HTML print path.

const SHEETS = {
  letter: { px: { width: 720, height: 960 }, format: "Letter" as const, pt: [612, 792] },
  a4: { px: { width: 698, height: 1027 }, format: "A4" as const, pt: [595, 842] },
};

let seed: E2eSeed;
let routes: Record<string, string>;

test.beforeAll(async () => {
  seed = await seedE2eStudio();
  await sql(`insert into public.studio_payment_jurisdictions (studio_id, payment_country, payment_currency, source, verification_reference) values ($1,'CA','cad','operator','synthetic')`, [seed.studioId]);
  const { clientId } = await seedE2eClient(seed);
  await sql(`update public.clients set name='Alexandria Montgomery-Featherstonehaugh', preferred_name='Alexandria Montgomery-Featherstonehaugh' where id=$1`, [clientId]);
  const serviceId = await getE2eServiceId(seed.studioId);
  const owner = await getOwnerPractitionerId(seed.studioId);
  for (let i = 0; i < 16; i++) {
    const [{ id }] = await sql<{ id: string }>(
      `insert into public.appointments (studio_id, practitioner_id, client_id, service_id, starts_at, ends_at, blocked_ends_at, duration_minutes, buffer_minutes_snapshot, status)
       values ($1,$2,$3,$4, now() - ($5 || ' hours')::interval, now() - ($5 || ' hours')::interval + interval '60 minutes', now() - ($5 || ' hours')::interval + interval '60 minutes', 60, 0, 'completed') returning id`,
      [seed.studioId, owner, clientId, serviceId, String(30 + i * 7)],
    );
    await sql(`insert into public.appointment_settlements (studio_id, appointment_id, method, amount_cents, currency, quoted_amount_cents, recorded_by_practitioner_id) values ($1,$2,$3,$4,'cad',$4,$5)`, [seed.studioId, id, i % 2 ? "paid_e_transfer" : "paid_cash", 12000 + i * 1111, owner]);
  }
  for (let i = 0; i < 12; i++) {
    await seedE2eProbeInventoryItem(seed, { lotNumber: `LOT-${i}-SYNTHETIC-LONG-LOT-NUMBER`, description: "Sterex Gold F3 probe synthetic long description for wrapping checks" });
    await seedE2eOverdueDisinfectant(seed, { name: `Barbicide E2E jar number ${i} with a long name`, datePrepared: "2026-10-01", discardDueDate: "2026-11-01" });
  }
  await sql(`insert into public.client_clinical_notes (client_id, studio_id, practitioner_id, kind, body, areas) select $1,$2,$3,'consultation', repeat('Synthetic consultation sentence for print layout. ', 40), array['Upper lip','Chin'] from generate_series(1,6)`, [clientId, seed.studioId, owner]);
  const [{ ym }] = await sql<{ ym: string }>(`select to_char(now(),'YYYY-MM') as ym`);
  routes = {
    statement: `/financials/statements/${clientId}/print?month=${ym}`,
    "sterile records": `/records/print?section=sterile`,
    "disinfectant records": `/records/print?section=disinfectants`,
    "clinical notes": `/clients/${clientId}/clinical-notes/print`,
  };
});

/** What the sheet would show: sticking-out boxes, app chrome that is still displayed, and text too light for white paper. */
async function audit(page: Page) {
  return page.evaluate(() => {
    const cv = document.createElement("canvas");
    cv.width = cv.height = 1;
    const cx = cv.getContext("2d")!;
    const rgb = (c: string) => {
      cx.clearRect(0, 0, 1, 1);
      cx.fillStyle = "#fff";
      cx.fillStyle = c;
      cx.fillRect(0, 0, 1, 1);
      return Array.from(cx.getImageData(0, 0, 1, 1).data.slice(0, 3));
    };
    const lum = ([r, g, b]: number[]) => {
      const f = (v: number) => ((v /= 255) <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4);
      return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b);
    };
    const vw = document.documentElement.clientWidth;
    const shown = (el: Element) => {
      const s = getComputedStyle(el);
      const r = el.getBoundingClientRect();
      return s.display !== "none" && s.visibility !== "hidden" && r.width > 0 && r.height > 0;
    };
    const name = (el: Element) => `${el.tagName.toLowerCase()} "${(el.textContent ?? "").trim().slice(0, 30)}"`;
    const sticksOut: string[] = [];
    const tooLight: string[] = [];
    for (const el of Array.from(document.body.querySelectorAll("*"))) {
      if (!shown(el)) continue;
      const r = el.getBoundingClientRect();
      if (r.right > vw + 1 || r.left < -1) sticksOut.push(`${name(el)} ${Math.round(r.left)}..${Math.round(r.right)}`);
      if (Array.from(el.childNodes).some((c) => c.nodeType === 3 && (c.textContent ?? "").trim() !== "")) {
        const ratio = 1.05 / (lum(rgb(getComputedStyle(el).color)) + 0.05);
        if (ratio < 4.5) tooLight.push(`${name(el)} ratio ${ratio.toFixed(2)}`);
      }
    }
    const chrome = Array.from(document.querySelectorAll("header, nav, footer, button, a[href], [role=navigation]"))
      .filter((e) => shown(e) && !(e.tagName === "HEADER" && e.closest("main")))
      .map(name);
    return { scrollWidth: document.documentElement.scrollWidth, vw, sticksOut, chrome, tooLight, text: document.body.innerText };
  });
}

for (const [sheetName, sheet] of Object.entries(SHEETS)) {
  test(`print preview on ${sheetName.toUpperCase()}: nothing clipped, only the document prints, text readable, a real PDF at the sheet size`, async ({ browser }) => {
    test.setTimeout(240_000);
    const ctx = await browser.newContext({ viewport: sheet.px });
    const page = await ctx.newPage();
    try {
      await loginAsOwner(page, seed);
      for (const [doc, route] of Object.entries(routes)) {
        await page.goto(route, { waitUntil: "load" });
        for (const theme of ["light", "dark"] as const) {
          await page.evaluate((t) => document.documentElement.classList.toggle("dark", t === "dark"), theme);
          await page.emulateMedia({ media: "print" });
          const a = await audit(page);
          const label = `${doc}, ${sheetName}, ${theme} theme`;
          expect(a.text.length, `${label}: the document rendered`).toBeGreaterThan(200);
          expect(a.scrollWidth, `${label}: no horizontal overflow`).toBeLessThanOrEqual(a.vw);
          expect(a.sticksOut, `${label}: nothing sticks out of the sheet`).toEqual([]);
          expect(a.chrome, `${label}: no app chrome prints`).toEqual([]);
          expect(a.tooLight, `${label}: text is dark enough for white paper`).toEqual([]);
          if (doc === "statement") {
            expect(a.text, `${label}: the total is printed`).toMatch(/Total paid \$[\d,]+\.\d{2}/);
            expect(a.text, `${label}: the balance is printed`).toMatch(/Balance due \$[\d,]+\.\d{2}/);
          }
          if (theme === "light") {
            const pdf = await PDFDocument.load(await page.pdf({ format: sheet.format, printBackground: false, margin: { top: "0.5in", bottom: "0.5in", left: "0.5in", right: "0.5in" } }));
            expect(pdf.getPageCount(), `${label}: the PDF has pages`).toBeGreaterThanOrEqual(2);
            const { width, height } = pdf.getPage(0).getSize();
            // Chromium reports A4 as 595.92 x 842.88 pt; allow the rounding, not another paper size.
            expect(Math.abs(width - sheet.pt[0]), `${label}: the PDF is the sheet's width`).toBeLessThanOrEqual(2);
            expect(Math.abs(height - sheet.pt[1]), `${label}: the PDF is the sheet's height`).toBeLessThanOrEqual(2);
          }
          await page.emulateMedia({ media: null });
        }
      }
    } finally {
      await ctx.close();
    }
  });
}
